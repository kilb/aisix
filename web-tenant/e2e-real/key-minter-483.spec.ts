import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { expect, test } from "@playwright/test";
import { ApiClient } from "../e2e/stack";

const session = process.env.KEY_MINTER_QA_SESSION!;
const state = JSON.parse(readFileSync(join(session, "public.json"), "utf8"));
const auth = JSON.parse(readFileSync(join(session, "local-auth.json"), "utf8"));
if (!state.ready || state.realBackend !== true || state.mockUpstream !== false || !["127.0.0.1", "localhost"].includes(new URL(state.httpUrl).hostname)) throw new Error("A real isolated loopback control plane is required");

// 组织密钥与个人密钥使用不同的离职合同；断言只取真实 API 与页面可见状态。
test("organization keys retain their named minter when the minter is disabled and removed", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  const suffix = randomUUID().slice(0, 8);
  const password = `Key-minter-${suffix}-483`;
  const owner = { email: `owner-${suffix}@key-minter.test`, password };
  const operator = new ApiClient(state.httpUrl);
  await operator.post("/admin/login", auth.operator);
  const signup = await new ApiClient(state.httpUrl).post("/api/signup", { org_name: `密钥创建者 ${suffix}`, ...owner });
  await operator.post(`/admin/tenants/${signup.tenant.id}/approve`);
  const ownerApi = new ApiClient(state.httpUrl);
  await ownerApi.post("/api/login", owner);
  const creatorName = `创建者 ${suffix}`;
  const creator = await ownerApi.post("/api/members", { email: `admin-${suffix}@key-minter.test`, password, display_name: creatorName, role: "admin" });
  const creatorApi = new ApiClient(state.httpUrl);
  await creatorApi.post("/api/login", { email: `admin-${suffix}@key-minter.test`, password });
  const minted = await creatorApi.post("/api/keys", { label: `组织密钥 ${suffix}`, member_id: null });
  const personal = await creatorApi.post("/api/keys", { label: `个人密钥 ${suffix}` });
  const platform = await operator.post(`/admin/tenants/${signup.tenant.id}/keys`, { label: `平台创建 ${suffix}` });
  const expected = { kind: "member", id: creator.id, display_name: creatorName };
  expect(minted.key.owner).toBeNull();
  expect(minted.key.created_by).toEqual(expected);
  await page.goto(`${state.tenantUrl.replace(/\/$/, "")}/login`);
  await page.getByLabel("邮箱", { exact: true }).fill(owner.email);
  await page.getByLabel("口令", { exact: true }).fill(owner.password);
  const login = page.waitForResponse(response => new URL(response.url()).pathname === "/api/login" && response.request().method() === "POST");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  expect((await login).status()).toBe(200);
  await page.goto(state.tenantUrl + "/#keys");
  await expect(page.getByRole("heading", { name: "API 密钥", exact: true })).toBeVisible();
  await expect(page.getByText("组织密钥归组织所有；创建者被停用或移除后仍保留，不会自动吊销。")).toBeVisible();
  const row = page.getByRole("row").filter({ has: page.getByRole("link", { name: minted.key.label, exact: true }) });
  await expect(row.locator('[data-label="归属"]')).toHaveText("组织");
  await expect(row.locator('[data-label="创建者"]')).toHaveText(creatorName);
  const platformRow = page.getByRole("row").filter({ has: page.getByRole("link", { name: platform.key.label, exact: true }) });
  await expect(platformRow.locator('[data-label="创建者"]')).toHaveText("平台管理员");
  const visiblePlatform = await ownerApi.get(`/api/keys/${platform.key.id}`);
  expect(visiblePlatform.created_by).toEqual({ kind: "operator", id: null, display_name: null });
  expect(JSON.stringify(visiblePlatform)).not.toContain(platform.key.created_by.id);
  await operator.patch(`/admin/members/${creator.id}`, { disabled: true });
  const disabledView = await ownerApi.get(`/api/keys/${minted.key.id}`);
  expect(disabledView).toMatchObject({ owner: null, disabled: false, disabled_by_platform: false, created_by: expected });
  const disabledAdmin = await operator.get(`/admin/keys/${minted.key.id}`);
  expect(disabledAdmin.effective_disabled).toBe(false);
  const personalDisabled = await operator.get(`/admin/keys/${personal.key.id}`);
  expect(personalDisabled.effective_disabled).toBe(true);
  await ownerApi.del(`/api/members/${creator.id}`);
  const retained = await ownerApi.get(`/api/keys/${minted.key.id}`);
  expect(retained).toMatchObject({ owner: null, disabled: false, disabled_by_platform: false, created_by: expected });
  const retainedAdmin = await operator.get(`/admin/keys/${minted.key.id}`);
  expect(retainedAdmin.effective_disabled).toBe(false);
  expect((await ownerApi.request("GET", `/api/keys/${personal.key.id}`)).status).toBe(404);
  await page.reload();
  await expect(row.locator('[data-label="创建者"]')).toHaveText(creatorName);
  await expect(row.locator('[data-label="状态"]')).toContainText("可用");
  expect(errors).toEqual([]);
  await page.screenshot({ path: join(process.env.KEY_MINTER_QA_OUTPUT!, "key-minter-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await row.locator('[data-label="创建者"]').scrollIntoViewIfNeeded();
  await expect(row.locator('[data-label="创建者"]')).toBeInViewport();
  await page.screenshot({ path: join(process.env.KEY_MINTER_QA_OUTPUT!, "key-minter-mobile.png") });
});
