import { randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { expect, test } from "@playwright/test";
import { ApiClient } from "../e2e/stack";

const session = process.env.KEY_MINTER_QA_SESSION!;
const state = JSON.parse(readFileSync(join(session, "public.json"), "utf8"));
const auth = JSON.parse(readFileSync(join(session, "local-auth.json"), "utf8"));
if (!state.ready || state.realBackend !== true || state.mockUpstream !== false || !["127.0.0.1", "localhost"].includes(new URL(state.httpUrl).hostname)) throw new Error("A real isolated loopback control plane is required");

// 新建模型允许暂不定价，明确当前基准价与分组换算率合同，入口到现行价格页。
test("creating an unpriced public model shows the current CNY pricing path", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.goto(state.adminUrl);
  await page.getByLabel("邮箱", { exact: true }).fill(auth.operator.email);
  await page.getByLabel("口令", { exact: true }).fill(auth.operator.password);
  const login = page.waitForResponse(response => new URL(response.url()).pathname === "/admin/login" && response.request().method() === "POST");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  expect((await login).status()).toBe(200);
  await page.goto(state.adminUrl + "/#public-routes");
  await expect(page.getByRole("heading", { name: "公共模型与路由", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "新建公共模型", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "新建公共模型", exact: true });
  await expect(dialog).toContainText("基准价与分组换算率");
  const name = `pricing-guide-${randomUUID().slice(0, 8)}`;
  await dialog.getByLabel("名称", { exact: true }).fill(name);
  const created = page.waitForResponse(response => new URL(response.url()).pathname === "/admin/public-models" && response.request().method() === "POST");
  await dialog.getByRole("button", { name: "新建", exact: true }).click();
  const response = await created;
  expect(response.status()).toBe(201);
  const model = await response.json();
  expect(response.request().postDataJSON()).toEqual({ name });
  expect(model.name).toBe(name);
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  const guidance = page.getByRole("status", { name: "模型定价提示", exact: true });
  await expect(guidance).toContainText("未定价");
  await expect(guidance).toContainText("基准价");
  await expect(guidance).toContainText("用量会保留为未定价记录");
  const admin = new ApiClient(state.httpUrl);
  await admin.post("/admin/login", auth.operator);
  const models = await admin.get("/admin/public-models");
  expect(models.items.filter((row: { id: string }) => row.id === model.id)).toHaveLength(1);
  const baselines = await admin.get("/admin/pricing/baselines");
  const baseline = baselines.items.find((row: { model_id: string }) => row.model_id === model.id);
  expect(baseline?.current ?? null).toBeNull();
  await expect(page.getByRole("status", { name: "模型定价提示", exact: true })).toContainText("未定价：无基准价");
  await expect(page.getByRole("status", { name: "模型定价提示", exact: true })).toContainText("需要重新计价才能补记费用");
  await page.screenshot({ path: join(process.env.KEY_MINTER_QA_OUTPUT!, "model-pricing-guide-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: join(process.env.KEY_MINTER_QA_OUTPUT!, "model-pricing-guide-mobile.png") });
  await guidance.getByRole("button", { name: "前往价格设置", exact: true }).click();
  await expect(page).toHaveURL(/#pricing\?section=baselines$/);
  await expect(page.getByRole("heading", { name: "基准价", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
